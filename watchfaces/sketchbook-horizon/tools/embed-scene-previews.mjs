/**
 * Inlines each scene's theme-preview screenshots as base64 for the settings page.
 *
 * The Scene Palette picker shows a day and a night shot of the chosen palette, and which scene
 * those shots are of follows the Scene setting. The stock thumbnails generator inlines one set per
 * face, so this builds the four sets the merged face needs, one per scene, keyed by scene then by
 * the palette's value.
 *
 * The screenshots already live in .github/images/<scene>/, the same ones the README galleries use.
 * Run it with `npm run gen:scene-previews` after changing those pictures.
 *
 * Input:  ../../../.github/images/<scene>/<platform>_<name>[_night].png
 * Output: src/pkjs/clay/scene-previews.g.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const imagesRoot = path.resolve(here, '../../../.github/images');
const outFile = path.resolve(here, '../src/pkjs/clay/scene-previews.g.js');

const SCENES = ['ridgeline', 'shoreline', 'skyline', 'treeline'];
const PLATFORMS = ['emery', 'gabbro'];
// the palette value the settings page saves, and the name its screenshots are filed under
const THEMES = [
  [0, 'sketchbook'],
  [1, 'daybreak'],
  [2, 'alpenglow'],
  [3, 'blueprint'],
  [4, 'forest'],
  [5, 'mono'],
  [6, 'cyberpunk'],
  [7, 'neo-tokyo'],
];

/** One PNG as a data URL, failing loudly so a missing or renamed shot stops the run. */
function dataUrl(file) {
  if (!fs.existsSync(file)) {
    throw new Error(`missing preview screenshot: ${path.relative(imagesRoot, file)}`);
  }
  return `data:image/png;base64,${fs.readFileSync(file).toString('base64')}`;
}

const previews = {};
for (const scene of SCENES) {
  const byTheme = {};
  for (const [value, name] of THEMES) {
    const byPlatform = {};
    for (const platform of PLATFORMS) {
      const dir = path.join(imagesRoot, scene);
      byPlatform[platform] = [
        dataUrl(path.join(dir, `${platform}_${name}.png`)),
        dataUrl(path.join(dir, `${platform}_${name}_night.png`)),
      ];
    }
    byTheme[String(value)] = byPlatform;
  }
  previews[scene] = byTheme;
}

const banner = [
  '// generated by tools/embed-scene-previews.mjs',
  '// do not edit by hand: run `npm run gen:scene-previews` after changing the pictures',
  '',
].join('\n');

fs.writeFileSync(outFile, `${banner}module.exports = ${JSON.stringify(previews, null, 2)};\n`);
console.log(`wrote ${path.relative(path.resolve(here, '..'), outFile)} for ${SCENES.length} scenes`);
