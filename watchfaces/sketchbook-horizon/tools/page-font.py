"""
Inlines a Latin subset of Patrick Hand as a web font for the settings page.

The page sets every word in Patrick Hand, the hand the watch draws its clock with. Loading it from
Google Fonts makes the Pebble app ask the wearer to allow fonts.googleapis.com once plugins are on,
and leaves a plain sans offline. So the page carries the font itself, as a WOFF2 in a data URL.

The whole font is about 215 KB, so this keeps only the Latin letters, punctuation, and symbols a
settings page shows, Vietnamese and the rest of the Latin script included, so a saved place such as
Łódź or Đà Nẵng still draws in the hand. The OFL reserves the name Patrick Hand for the font
as published, and a subset counts as a modified version, so it is renamed Sketchbook Hand inside the
file and on the page.

Run it with `npm run gen:page-font` after changing the font or the characters it keeps. It needs
Python with fontTools and brotli.

Input:  resources/fonts/PatrickHand-Regular.ttf
Output: src/pkjs/clay/page-font.g.js
"""
import base64
import io
import os

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, '..', 'resources', 'fonts', 'PatrickHand-Regular.ttf')
OUTPUT = os.path.join(HERE, '..', 'src', 'pkjs', 'clay', 'page-font.g.js')
FAMILY = 'Sketchbook Hand'

# printable ASCII, Latin-1, Latin Extended A and B, the Vietnamese letters, the dashes, quotes,
# bullet, and ellipsis, the per mille and angle quotes, and the euro and trademark signs
KEPT = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x250)) + list(range(0x1EA0, 0x1F00))
        + list(range(0x2010, 0x2028)) + list(range(0x2030, 0x203B)) + [0x20AC, 0x2122])

# every name record that says which font this is, so the reserved name appears in none of them. the
# copyright and licence records stay as they are
NAMES = {
    1: FAMILY,
    3: 'SketchbookHand-Regular',
    4: FAMILY + ' Regular',
    6: 'SketchbookHand-Regular',
    16: FAMILY,
    18: FAMILY + ' Regular',
}


def build():
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True

    font = TTFont(SOURCE)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=KEPT)
    subsetter.subset(font)

    for record in font['name'].names:
        if record.nameID in NAMES:
            record.string = NAMES[record.nameID]

    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer)
    encoded = base64.b64encode(buffer.getvalue()).decode('ascii')

    rule = ("@font-face { font-family: '%s'; font-style: normal; font-weight: 400; font-display: swap; "
            "src: url(data:font/woff2;base64,%s) format('woff2'); }") % (FAMILY, encoded)
    banner = ('// generated by tools/page-font.py\n'
              '// do not edit by hand: run `npm run gen:page-font` after changing the font or the characters it keeps\n')

    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as out:
        out.write(banner + 'module.exports = { family: %r, rule: %r };\n' % (FAMILY, rule))

    print('wrote src/pkjs/clay/page-font.g.js, %d KB of font' % (len(buffer.getvalue()) // 1024))


if __name__ == '__main__':
    build()
