/**
 * Inlines the desktop and theme preview screenshots as base64 for the settings page.
 *
 * The Desktop picker shows a shot of each desktop, and the Editor Theme picker a shot of the VS Code
 * desktop in each theme. The stock theme-previews generator inlines one picker's shots, so this
 * builds both maps, each keyed by the value its picker saves.
 *
 * The screenshots live in .github/images/ide-vscode/, beside the ones the README uses. A shot that
 * is not there yet is skipped with a warning, and its row in the picker shows the name alone, so
 * the page still builds before every shot is taken.
 *
 * `--from=<folder>` first copies a tap-walk of the `previews` walk into place. The walk shows the
 * five desktops and then VS Code in each theme after Dark, so its ten shots land in that order,
 * and the first one is both the VS Code desktop and the Dark theme.
 *
 * Run it with `npm run gen:previews` after changing the pictures.
 *
 * Input:  ../../../.github/images/ide-vscode/desktop_<name>.png and theme_<name>.png
 * Output: src/pkjs/clay/previews.g.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const unit = path.resolve(here, '..');
const imagesDir = path.resolve(here, '../../../.github/images/ide-vscode');
const outFile = path.resolve(here, '../src/pkjs/clay/previews.g.js');

// the value each picker saves, and the name its screenshot is filed under
const DESKTOPS = [
  [0, 'vscode'],
  [1, 'win95'],
  [2, 'win2000'],
  [3, 'dos'],
  [4, 'dos-ide'],
];
const THEMES = [
  [0, 'dark'],
  [1, 'light'],
  [2, 'terminal'],
  [3, 'cyberpunk'],
  [4, 'synthwave'],
  [5, 'mono'],
];

// the files each tap-walk shot is copied to, in the walk's order
const WALK_SHOTS = [
  ['desktop_vscode.png', 'theme_dark.png'],
  ['desktop_win95.png'],
  ['desktop_win2000.png'],
  ['desktop_dos.png'],
  ['desktop_dos-ide.png'],
  ['theme_light.png'],
  ['theme_terminal.png'],
  ['theme_cyberpunk.png'],
  ['theme_synthwave.png'],
  ['theme_mono.png'],
];

/** Copies a tap-walk's shots into the images folder under the names the pickers read. */
function copyWalk(folder) {
  const from = path.resolve(unit, folder);
  const shots = fs.readdirSync(from).filter((file) => /^shot_\d{3}\.png$/.test(file)).sort();

  // a walk that saved a different number of screens has two steps drawing the same picture, or
  // stopped early, and the names would land on the wrong shots
  if (shots.length !== WALK_SHOTS.length) {
    throw new Error(`expected ${WALK_SHOTS.length} shots in ${folder}, found ${shots.length}`);
  }

  shots.forEach((shot, index) => {
    for (const name of WALK_SHOTS[index]) {
      fs.copyFileSync(path.join(from, shot), path.join(imagesDir, name));
    }
  });
  console.log(`copied ${shots.length} shots from ${folder}`);
}

/** Each value's shot as a one-picture list, leaving out a value whose shot is not there yet. */
function previewsFor(prefix, rows) {
  const previews = {};

  for (const [value, name] of rows) {
    const file = path.join(imagesDir, `${prefix}_${name}.png`);

    if (!fs.existsSync(file)) {
      console.warn(`no preview yet: ${path.relative(unit, file)}`);
      continue;
    }

    previews[String(value)] = [`data:image/png;base64,${fs.readFileSync(file).toString('base64')}`];
  }

  return previews;
}

const fromArg = process.argv.slice(2).find((arg) => arg.startsWith('--from='));
if (fromArg) {
  copyWalk(fromArg.slice('--from='.length));
}

const previews = {
  desktop: previewsFor('desktop', DESKTOPS),
  theme: previewsFor('theme', THEMES),
};

const banner = [
  '// generated by tools/embed-previews.mjs',
  '// do not edit by hand: run `npm run gen:previews` after changing the pictures',
  '',
].join('\n');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${banner}module.exports = ${JSON.stringify(previews, null, 2)};\n`);
console.log(`wrote ${path.relative(unit, outFile)}`);
