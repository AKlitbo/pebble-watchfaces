"""
Inlines Latin subsets of VT323 and Share Tech Mono as web fonts for the settings page.

The page sets its window titles and the Save button in VT323 and everything else in Share Tech Mono,
the two faces the desktops draw with. Loading them from Google Fonts makes the Pebble app ask the
wearer to allow fonts.googleapis.com once plugins are on, and leaves a plain sans offline. So the page
carries both fonts itself, as WOFF2s in data URLs.

Each keeps only the Latin letters, punctuation, and symbols a settings page shows, so a saved place
such as Lodz or Da Nang with its accents still draws in the font. The OFL reserves the name Share for
Share Tech Mono as published, and a subset counts as a modified version, so that one is renamed
Runtime Mono inside the file and on the page. VT323 reserves no name and keeps its own.

Run it with `npm run gen:page-font` after changing a font or the characters it keeps. It needs
Python with fontTools and brotli.

Input:  resources/fonts/VT323-Regular.ttf and resources/fonts/ShareTechMono-Regular.ttf
Output: src/pkjs/clay/page-font.g.js
"""
import base64
import io
import json
import os

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, '..', 'resources', 'fonts')
OUTPUT = os.path.join(HERE, '..', 'src', 'pkjs', 'clay', 'page-font.g.js')

# printable ASCII, Latin-1, Latin Extended A and B, the Vietnamese letters, the dashes, quotes,
# bullet, and ellipsis, the per mille and angle quotes, the euro and trademark signs, and the
# triangles and check mark the page's buttons and boxes draw
KEPT = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x250)) + list(range(0x1EA0, 0x1F00))
        + list(range(0x2010, 0x2028)) + list(range(0x2030, 0x203B)) + [0x20AC, 0x2122]
        + [0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x2713])

# the page's name for each font, and the file it is cut from. a name of None keeps the font's own
SOURCES = [
    ('title', 'VT323-Regular.ttf', 'VT323', None),
    ('body', 'ShareTechMono-Regular.ttf', 'Runtime Mono', 'RuntimeMono-Regular'),
]


def cut(file, family, postscript):
    """One font's subset as a WOFF2, renamed in every record that says which font it is."""
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True

    font = TTFont(os.path.join(FONTS, file))
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=KEPT)
    subsetter.subset(font)

    # the copyright and licence records stay as they are
    if postscript:
        names = {1: family, 3: postscript, 4: family + ' Regular', 6: postscript, 16: family, 18: family + ' Regular'}
        for record in font['name'].names:
            if record.nameID in names:
                record.string = names[record.nameID]

    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def build():
    out = {}
    rules = []
    sizes = []

    for role, file, family, postscript in SOURCES:
        data = cut(file, family, postscript)
        encoded = base64.b64encode(data).decode('ascii')
        rules.append(("@font-face { font-family: '%s'; font-style: normal; font-weight: 400; font-display: swap; "
                      "src: url(data:font/woff2;base64,%s) format('woff2'); }") % (family, encoded))
        out[role] = family
        sizes.append('%s %d KB' % (family, len(data) // 1024))

    out['rule'] = '\n'.join(rules)
    banner = ('// generated by tools/page-font.py\n'
              '// do not edit by hand: run `npm run gen:page-font` after changing a font or the characters it keeps\n')

    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(banner + 'module.exports = ' + json.dumps(out, indent=2) + ';\n')

    print('wrote src/pkjs/clay/page-font.g.js, ' + ', '.join(sizes))


if __name__ == '__main__':
    build()
