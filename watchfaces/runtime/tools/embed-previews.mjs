/**
 * Inlines the theme preview screenshots as base64 for the settings page.
 *
 * The Editor Theme picker shows the VS Code desktop in each theme, and the Desktop Theme picker the
 * chosen desktop in its Classic, Dark, and Terminal looks. The stock theme-previews generator inlines
 * one picker's shots, so this builds both maps, each keyed by the value its picker saves. The Desktop
 * Theme map is keyed by desktop first, since its shots follow the Desktop dropdown.
 *
 * The screenshots live in .github/images/runtime/, beside the ones the README uses. A shot that
 * is not there yet is skipped with a warning, and its row in the picker shows the name alone, so
 * the page still builds before every shot is taken.
 *
 * `--from=<folder>` first copies a tap-walk of the `previews` walk into place. The walk shows the
 * six desktops, then VS Code in each theme after Dark, then each other desktop in Terminal, then
 * each in Dark, so its shots land in that order. The first one is the VS Code desktop in Dark.
 *
 * Run it with `npm run gen:previews` after changing the pictures.
 *
 * Input:  ../../../.github/images/runtime/desktop_<name>.png and desktop_<name>_<look>.png, where
 *         VS Code's look is its theme
 * Output: src/pkjs/clay/previews.g.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const unit = path.resolve(here, '..');
const imagesDir = path.resolve(here, '../../../.github/images/runtime');
const outFile = path.resolve(here, '../src/pkjs/clay/previews.g.js');

// the value each picker saves, and the name its screenshot is filed under
const DESKTOPS = [
  [0, 'vscode'],
  [1, 'win95'],
  [2, 'win2000'],
  [3, 'dos'],
  [4, 'dos-ide'],
  [5, 'netbeans'],
];
// VS Code's Dark theme is its plain desktop shot, and each other theme carries the theme's name
const THEMES = [
  [0, 'vscode'],
  [1, 'vscode_light'],
  [2, 'vscode_terminal'],
  [3, 'vscode_cyberpunk'],
  [4, 'vscode_synthwave'],
  [5, 'vscode_mono'],
];

// the files each tap-walk shot is copied to, in the walk's order
const WALK_SHOTS = [
  ['desktop_vscode.png'],
  ['desktop_win95.png'],
  ['desktop_win2000.png'],
  ['desktop_dos.png'],
  ['desktop_dos-ide.png'],
  ['desktop_netbeans.png'],
  ['desktop_vscode_light.png'],
  ['desktop_vscode_terminal.png'],
  ['desktop_vscode_cyberpunk.png'],
  ['desktop_vscode_synthwave.png'],
  ['desktop_vscode_mono.png'],
  ['desktop_win95_terminal.png'],
  ['desktop_win2000_terminal.png'],
  ['desktop_dos_terminal.png'],
  ['desktop_dos-ide_terminal.png'],
  ['desktop_netbeans_terminal.png'],
  ['desktop_win95_dark.png'],
  ['desktop_win2000_dark.png'],
  ['desktop_dos_dark.png'],
  ['desktop_dos-ide_dark.png'],
  ['desktop_netbeans_dark.png'],
];

// the Desktop Theme picker's looks, by the value it saves, and the suffix each look's shot carries
const LOOKS = [
  [0, ''],
  [1, '_terminal'],
  [2, '_dark'],
];

/** Copies a tap-walk's shots into the images folder under the names the pickers read. */
function copyWalk(folder) {
  const from = path.resolve(unit, folder);
  const shots = fs.readdirSync(from).filter((file) => /^shot_\d{3}\.png$/.test(file)).sort();

  // a walk that saved a different number of screens has two steps drawing the same picture, or
  // stopped early, and the names would land on the wrong shots
  if (shots.length !== WALK_SHOTS.length) {
    throw new Error(`expected ${WALK_SHOTS.length} shots in ${folder}, found ${shots.length}`);
  }

  shots.forEach((shot, index) => {
    for (const name of WALK_SHOTS[index]) {
      fs.copyFileSync(path.join(from, shot), path.join(imagesDir, name));
    }
  });
  console.log(`copied ${shots.length} shots from ${folder}`);
}

/** Each value's shot as a one-picture list, leaving out a value whose shot is not there yet. */
function previewsFor(prefix, rows) {
  const previews = {};

  for (const [value, name] of rows) {
    const file = path.join(imagesDir, `${prefix}_${name}.png`);

    if (!fs.existsSync(file)) {
      console.warn(`no preview yet: ${path.relative(unit, file)}`);
      continue;
    }

    previews[String(value)] = [`data:image/png;base64,${fs.readFileSync(file).toString('base64')}`];
  }

  return previews;
}

const fromArg = process.argv.slice(2).find((arg) => arg.startsWith('--from='));
if (fromArg) {
  copyWalk(fromArg.slice('--from='.length));
}

// every desktop but VS Code, which has the Editor Theme picker instead
const desktopTheme = {};
for (const [value, name] of DESKTOPS.slice(1)) {
  desktopTheme[String(value)] = previewsFor('desktop', LOOKS.map(([look, suffix]) => [look, name + suffix]));
}

const previews = {
  theme: previewsFor('desktop', THEMES),
  desktopTheme,
};

const banner = [
  '// generated by tools/embed-previews.mjs',
  '// do not edit by hand: run `npm run gen:previews` after changing the pictures',
  '',
].join('\n');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${banner}module.exports = ${JSON.stringify(previews, null, 2)};\n`);
console.log(`wrote ${path.relative(unit, outFile)}`);
